/**
 * @file Passenger.ts
 * @description
 * מגדיר את מבנה הנתונים עבור נוסע במערכת.
 * ישות זו הכרחית לתמיכה בריבוי נוסעים באותה נסיעה (למשל זוג או משפחה).
 * היא מאפשרת למערכת לקשר בין כרטיס טיסה/דרכון ספציפי לאדם ספציפי,
 * ולייצר את ממשק הטאבים המהיר (Quick Switch Tabs) במסך העלייה למטוס.
 */

export interface Passenger {
  id: string;                      // מזהה ייחודי לנוסע (UUID)

  // פרטי זיהוי לתצוגה
  fullName: string;                // שם מלא כפי שחולץ מהכרטיס (למשל: "נחמן חסון")
  shortName: string;               // שם קצר שיוצג בטאב הקטן בתחתית המסך (למשל: "נחמן")

  // נתונים אישיים (מוצפנים מקומית)
  passportNumber?: string;         // מספר הדרכון (אם חולץ או הוזן ידנית)

  // קישור למצב הנוכחי בטיסה הפעילה
  currentSeatNumber?: string;      // מספר המושב בטיסה הנוכחית (למשל: "27E")
  currentBoardingPassId?: string;  // מזהה (ID) של מסמך כרטיס הטיסה שפעיל כרגע עבורו

  // הגדרות מערכת
  isPrimaryUser: boolean;          // האם זה בעל המכשיר הראשי (זה שיקבל את ההתראות המרכזיות)
}